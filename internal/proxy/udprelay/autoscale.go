package udprelay

// Шаг 4: слой решения между предложением градиента (Шаг 2, gradient.go) и
// реальным ресайзом hot-set'а (Шаг 3, sessionManager.growHotSet/shrinkHotSet).
// Прямой провод "предложение -> ресайз" сознательно НЕ сделан, см. ниже.
// Здесь только чистая функция: ни таймеров, ни горутин, ни часов - время
// считается тиками gradientLoop (gradientLogInterval = 30с), чтобы всё
// проверялось таблицей. Разбор всей механики словами, с определениями
// терминов - docs/hotset-autoscaler.md.
//
// Почему порог стоит на gradient, а НЕ на знаке (suggested - K):
// формула Шага 2 - raw = gradient*K + sqrt(K), то есть в неё зашит
// постоянный запас вверх на sqrt(K). Нейтральная точка (предложение равно
// текущему K) - там, где gradient ~ 1 - 1/sqrt(K): при K=30 это 0.817. А
// gradient = 1.2*minRTT/avgRTT, значит 0.817 - это avgRTT уже на 46% выше
// дна. Расти в такой момент - ровно наоборот от смысла.
// [ПРОВЕРЕНО 2026-08-30, 4 живых лога my1/my2/ренат/ростик, docs/*.txt,
// 13804 тика]: suggested > K в 91.8 / 88.4 / 87.8 / 43.1 % тиков - привязка
// по знаку (suggested - K) означала бы "расти всегда" на домашних линках и
// "падать всегда" на мобильном у Ростика. Поэтому пороги ниже - прямо на
// gradient, а suggestedHotSetSize остаётся тем, чем был на Шаге 2:
// диагностикой в логе и в CSV.

// autoscaleGrowGradient / autoscaleShrinkGradient - границы трёх зон.
// gradient = 1.2*minRTT/avgRTT, поэтому пороги читаются как чистая физика:
//
//	gradient >= 1.00  <=>  avgRTT <= 1.20 * minRTT  - канал у своего дна, растём
//	gradient <= 0.70  <=>  avgRTT >= 1.71 * minRTT  - канал заметно хуже дна, сжимаемся
//	между             <=>  avgRTT в 1.2-1.7 от дна  - нейтральная зона, не трогаем
//
// Широкая нейтральная зона (deadband) - главная защита от дёрганья на
// обычном джиттере: пока сигнал в ней, счётчик серии сбрасывается в ноль,
// то есть неоднозначный период не просто не даёт действия, а стирает уже
// накопленную уверенность. НЕ откалибровано живым прогоном - границы
// выбраны по разбросу gradient в четырёх логах (см. таблицу в
// docs/hotset-autoscaler.md, раздел "Откуда взялись числа").
const (
	autoscaleGrowGradient   = 1.00
	autoscaleShrinkGradient = 0.70
)

// autoscaleGrowRunTicks / autoscaleShrinkRunTicks - гистерезис: сколько
// тиков подряд сигнал должен стоять в одной зоне, прежде чем зона вообще
// получит право на действие. Один тик = gradientLogInterval = 30с, значит
// 6 тиков = 3 минуты, 4 тика = 2 минуты. Сжатие требует меньше
// подтверждений, чем рост: сжатие - отступление к заведомо рабочему
// состоянию, рост - трата TURN-аллокации.
const (
	autoscaleGrowRunTicks   = 6
	autoscaleShrinkRunTicks = 4
)

// autoscaleGrowCooldownTicks / autoscaleShrinkCooldownTicks - кулдаун:
// минимум тиков между двумя РЕАЛЬНЫМИ ресайзами. 10 тиков = 5 минут,
// 6 тиков = 3 минуты. Гистерезис отвечает за "сигнал не шум", кулдаун - за
// "не чаще, чем один шаг ±1 успевает отразиться на измерении": свежий слот
// поднимает DTLS+TURN и только потом начинает давать RTT, так что решать
// снова раньше, чем через несколько тиков, значит решать по данным, в
// которых предыдущего решения ещё не видно.
//
// Кулдаун считается от последнего реального изменения K, а не от попытки:
// попытка, упёршаяся в пол или потолок, ничего не меняет и кулдаун не жжёт.
const (
	autoscaleGrowCooldownTicks   = 10
	autoscaleShrinkCooldownTicks = 6
)

// autoscaleBounds - жёсткие пол и потолок для K. Потолок - ровно то K, с
// которым процесс стартовал (cfg.TURN.N), НЕ выше: квота TURN-аллокаций
// живёт по паре (credential, relay-кластер) и на рост выше проверенного N
// отвечает 486, то есть слот заведётся мёртвым. Значит расти автоскейлер
// может только назад, к твоему N, после собственного сжатия - excursion
// выше N это отдельная задача со своей логикой "рост не удался, откатись и
// не пробуй", и в Шаг 4 она не входит.
//
// Пол - половина N: сжатие это ставка ("часть роста RTT - наша собственная
// очередь, меньше путей = меньше очереди"), и она непроверена (см.
// gradient.go про неотличимость деградации от честно забитого канала).
// Половина N ограничивает цену проигранной ставки: больше половины полосы
// эта ставка отдать не может.
type autoscaleBounds struct {
	min, max int
}

func autoscaleBoundsFor(baseK int) autoscaleBounds {
	if baseK < 1 {
		baseK = 1
	}
	min := baseK / 2
	if min < 1 {
		min = 1
	}
	return autoscaleBounds{min: min, max: baseK}
}

// autoscaleDecider - вся память решающего слоя. Живёт в единственном
// экземпляре у sessionManager и трогается только из горутины gradientLoop,
// поэтому без мьютекса.
type autoscaleDecider struct {
	zone        int // зона предыдущего тика: +1 рост, -1 сжатие, 0 нейтраль
	run         int // сколько тиков подряд сигнал стоит в zone
	sinceAction int // тиков прошло с последнего РЕАЛЬНОГО изменения K
}

// autoscaleZone переводит gradient в зону. Отдельной функцией, чтобы порог
// проверялся тестом без прокрутки состояния.
func autoscaleZone(gradient float64) int {
	switch {
	case gradient >= autoscaleGrowGradient:
		return 1
	case gradient > 0 && gradient <= autoscaleShrinkGradient:
		return -1
	default:
		return 0
	}
}

// decide - один тик решающего слоя. Возвращает, на сколько менять K:
// +1 (растить), -1 (сжимать) или 0 (ничего не делать). Вызывать РОВНО раз
// на тик gradientLoop, включая тики, на которых автоскейлер выключен: тогда
// возврат идёт в dry-run-лог, состояние остаётся тёплым и включение на живую
// не начинает отсчёт заново.
//
// Второй возврат, refused, отделяет «сигнала на действие не было» от
// «действие было полностью подтверждено, но его съела граница диапазона»:
// +1 - отказан рост (K уже на потолке), -1 - отказано сжатие (K на полу),
// 0 - решать было нечего. Оба случая дают delta = 0, но означают разное, а на
// своём N потолок молчал бы ВСЕГДА - то есть нормой стало бы состояние, в
// котором по логу не отличить здоровый канал от постоянно отказываемого роста.
// [ПРОВЕРЕНО 2026-08-30 живьём на LTE: серия набралась дважды за 20 тиков,
// вторая дошла до попытки и была зажата потолком K=30=N - в логе не осталось
// ни строки.]
//
// gradient <= 0 (нет данных - см. suggestedHotSetSize) попадает в нейтраль и
// сбрасывает серию: отсутствие сигнала это не подтверждение здоровья.
//
// Порядок внутри тика ровно такой:
//  1. время идёт (sinceAction++) независимо от сигнала;
//  2. зона тика; смена зоны или нейтраль обнуляют серию;
//  3. серия набрана И кулдаун своей стороны истёк -> попытка;
//  4. попытка зажимается в [min, max]; если K после зажима не изменился -
//     это no-op, кулдаун не сбрасывается (упёрлись в границу, ждать нечего);
//  5. серия и зона обнуляются после любой попытки - следующее действие
//     потребует новой полной серии подтверждений, а не одного тика.
func (d *autoscaleDecider) decide(gradient float64, k int, b autoscaleBounds) (delta, refused int) {
	d.sinceAction++

	zone := autoscaleZone(gradient)
	if zone == 0 {
		d.zone, d.run = 0, 0
		return 0, 0
	}
	if zone == d.zone {
		d.run++
	} else {
		d.zone, d.run = zone, 1
	}

	needRun, needCooldown := autoscaleGrowRunTicks, autoscaleGrowCooldownTicks
	if zone < 0 {
		needRun, needCooldown = autoscaleShrinkRunTicks, autoscaleShrinkCooldownTicks
	}
	if d.run < needRun || d.sinceAction < needCooldown {
		return 0, 0
	}

	d.zone, d.run = 0, 0

	next := k + zone
	if next > b.max {
		next = b.max
	}
	if next < b.min {
		next = b.min
	}
	if next == k {
		return 0, zone
	}
	d.sinceAction = 0
	// Возврат всегда ±1, а не next-k: K вне [min,max] бывает только после
	// ручного stdin-"grow"/"shrink", и тогда зажим сам тянет K обратно в
	// диапазон по одному шагу за раз, а не прыжком.
	if next > k {
		return 1, 0
	}
	return -1, 0
}

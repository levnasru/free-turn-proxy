package udprelay

import (
	"math"
	"sync"
	"time"
)

// Шаг 2: считаем, что hot-set'у стоило бы быть размером K, но НЕ применяем -
// только логируем предложение (см. gradientLoop в sessionmgr.go). Адаптация
// gradient-контроллера (Envoy adaptive concurrency / Netflix concurrency-limits,
// оба - вариации TCP Vegas) под наш случай: вместо одного соединения и лимита
// concurrency у нас K параллельных путей и решение "сколько путей держать
// живыми". Сигнал - средний RTT по hot-set'у против скользящего baseline
// (минимум за последние minRTTResetInterval), а не RTT одного запроса.
//
// ⚠️ Известная слабина, ровно поэтому Шаг 2 - только лог, не применение:
// RTT растёт и под реальной деградацией пути, и просто когда канал честно
// забит (bufferbloat при максимальной отдаче/скачивании) - отличить одно от
// другого по одному только RTT нельзя (та же причина, по которой появился
// BBR - Vegas/Reno этого не различают). Прежде чем это управляло реальным K,
// нужно насмотреться на dry-run логи из живых сессий и сверить с тем, была
// ли скорость реально плохой в момент просадки RTT, а не просто канал занят
// своим делом.

// minRTTResetInterval - как часто baseline (минимум) сбрасывается и меряется
// заново, чтобы устойчивая деградация не осела навсегда как "норма" (тот же
// приём, что в Envoy - без джиттера, он там против синхронного ресета по
// всему флоту хостов, у нас один процесс).
//
// Изначально стояло 2 минуты - живой лог 2026-08-25 показал, что этого мало:
// RTT остаётся повышенным ещё ~20-30с ПОСЛЕ того, как [STATS] показывает
// down/up около нуля (канал реально простаивает) - похоже на bufferbloat,
// драйн буфера где-то на пути (модем/WG/relay) отстаёт от факта "трафика
// больше нет". При 2-минутном окне это означает, что весь спидтест+драйн
// укладывается в одно окно без единого по-настоящему простаивающего сэмпла -
// baseline подпёрло с 15.7мс до 21.8мс и он там и остался до конца окна.
// 15 минут - не рассчитано, ставка на то, что при обычном использовании
// (не сплошной спидтест) простой попадётся внутри окна чаще.
//
// Второй живой прогон (тем же вечером, окно временно уменьшено до 90с для
// проверки) поймал сам момент ресета: baseline вырос 23.79мс -> 31.34мс на
// почти простаивающем канале - ресет попал на неудачный тик, чистое
// невезение, не bufferbloat. Но уже через один следующий тик (30с)
// trещотка сама подтянула baseline обратно вниз (31.34 -> 16.42), как
// только пришёл честно низкий сэмпл - ресет для восстановления не
// понадобился. Вывод: основную работу по восстановлению делает трещотка
// вниз (наблюдение observe()), не ресет - ресет только даёт шанс попасть
// на неудачный момент, пользы от частых ресетов почти нет. Поэтому окно
// должно быть РЕДКИМ (ресет - страховка на случай, если условия
// действительно надолго изменились, а не рутинный механизм гигиены), а не
// частым. НЕ откалибровано живым замером ни в этом значении.
const minRTTResetInterval = 15 * time.Minute

// gradientBufferFraction - допуск поверх baseline до того, как численно
// считать деградацией (терпимость к обычному джиттеру). НЕ откалибровано.
const gradientBufferFraction = 0.2

// gradientResetSettleSamples - сколько сэмплов подряд после истечения окна
// накапливаем в кандидата на новое дно, прежде чем сделать его авторитетным
// baseline. Без этого один сэмпл, совпавший по времени со сбросом окна,
// немедленно становится "новым дном" - живой лог Рената (2026-08-29,
// gradient-log.csv) поймал именно это: сброс попал на avgRTT=1197ms посреди
// часового outage, minRTT стал 1197ms и держал gradient=1.200 ("канал в
// идеальном здоровье") все следующие 15 минут, хотя канал был мёртв.
// Улучшение (сэмпл ниже текущего дна) принимается немедленно всегда - это
// трещотка вниз, она безопасна (см. живые прогоны 2026-08-25 выше). Опасно
// только движение ВВЕРХ дна - его теперь придерживаем settle-периодом.
//
// Калибровка 2026-08-30 по 4 живым логам (my1/my2/ростик/ренат,
// docs/*.txt, симуляция логики observe() построчно): при settle=3 доля
// финализаций settle-периода, осевших на дне >2x медианного RTT устройства
// (то есть settle не отфильтровал короткий бёрст-шум), у Ростика - 19 из
// 106 (мобильная сеть с частыми короткими всплесками 200-750мс на фоне
// медианы ~56мс). При settle=7 - 1 из 92, у остальных трёх логов - без
// ухудшения (my1 7->4, my2 0->0, реальный аутэйдж Рената как и раньше
// правильно поднимает дно, только чуть позже). Дальше (9/11/15) прирост
// почти нулевой, а задержка подтверждения только растёт - 7 практическая
// точка отсечения. Задержка не создаёт риска ложного "здоровья": пока
// settle не набрался, авторитетным остаётся старое (заниженное) дно, то
// есть suggested_k консервативен, а не оптимистичен, все время ожидания.
const gradientResetSettleSamples = 7

// gradientTracker хранит скользящий baseline (минимум среднего RTT hot-set'а)
// с периодическим сбросом окна.
type gradientTracker struct {
	mu          sync.Mutex
	minRTT      time.Duration
	windowStart time.Time

	settlePending time.Duration // кандидат на новое (более высокое) дно после сброса окна
	settleCount   int           // сэмплов накоплено в кандидата; 0 = не в settle-режиме
}

func newGradientTracker() *gradientTracker {
	return &gradientTracker{windowStart: time.Now()}
}

// observe обновляет baseline очередным средним RTT hot-set'а за тик.
//
// Ратчет вниз (avgRTT < текущее дно) принимается всегда немедленно - это
// безопасно, см. живые прогоны 2026-08-25 в комментарии выше про
// minRTTResetInterval. Движение дна ВВЕРХ (после истечения окна) - нет:
// первый сэмпл после сброса только открывает settle-период
// (gradientResetSettleSamples сэмплов), старое дно остаётся авторитетным
// (baseline() возвращает его), пока settle не наберёт нужное число сэмплов -
// тогда новым дном становится их минимум, а не первый попавшийся.
func (g *gradientTracker) observe(avgRTT time.Duration) {
	g.mu.Lock()
	defer g.mu.Unlock()

	if g.settleCount == 0 && time.Since(g.windowStart) >= minRTTResetInterval {
		g.windowStart = time.Now()
		g.settlePending = avgRTT
		g.settleCount = 1
	} else if g.settleCount > 0 {
		if avgRTT < g.settlePending {
			g.settlePending = avgRTT
		}
		g.settleCount++
		if g.settleCount >= gradientResetSettleSamples {
			g.minRTT = g.settlePending
			g.settleCount = 0
			return
		}
	}

	if g.minRTT == 0 || avgRTT < g.minRTT {
		g.minRTT = avgRTT
	}
}

func (g *gradientTracker) baseline() time.Duration {
	g.mu.Lock()
	defer g.mu.Unlock()
	return g.minRTT
}

// suggestedHotSetSize - чистая часть формулы, без сайд-эффектов, чтобы
// проверяться таблицей без таймеров/горутин. avgRTT<=0 или minRTT<=0
// (данных ещё нет) - предложение равно текущему K, без деления на ноль.
// Предложение зажато в [1, currentK*3] - Шаг 2 не решает, какие границы
// разумны в бою, это вопрос Шага 3; тут только чтобы одиночный кривой сэмпл
// не напечатал в лог отрицательное или заоблачное число.
func suggestedHotSetSize(currentK int, avgRTT, minRTT time.Duration) (gradient float64, suggested int) {
	if avgRTT <= 0 || minRTT <= 0 || currentK <= 0 {
		return 0, currentK
	}
	buffer := time.Duration(float64(minRTT) * gradientBufferFraction)
	gradient = float64(minRTT+buffer) / float64(avgRTT)
	headroom := math.Sqrt(float64(currentK))
	raw := gradient*float64(currentK) + headroom

	suggested = int(math.Round(raw))
	if suggested < 1 {
		suggested = 1
	}
	if max := currentK * 3; suggested > max {
		suggested = max
	}
	return gradient, suggested
}
